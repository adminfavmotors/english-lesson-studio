import React from 'react';
import { createRoot } from 'react-dom/client';
import App from './App';
import './app.css';
import { APP_LANGUAGE } from './app-language';
import { canonicalAppUrl } from './app-routes';
document.documentElement.lang = APP_LANGUAGE;
const canonicalUrl = canonicalAppUrl(location.href);
if (canonicalUrl.href !== location.href) history.replaceState(null, '', canonicalUrl);
createRoot(document.getElementById('root')!).render(<React.StrictMode><App /></React.StrictMode>);
